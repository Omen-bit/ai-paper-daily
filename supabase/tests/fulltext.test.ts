// Run with: node --experimental-strip-types --test supabase/tests/fulltext.test.ts
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  decode, fullInput, NOT_IN_PAPER, parseArxivHtml, parseFullAnswer, searchText, toPassages, usable,
} from "../functions/_shared/fulltext.ts";

// A small page in the layout arXiv's HTML (LaTeXML) uses
const PAGE = `<!DOCTYPE html><html><head><title>Paper</title><style>.x{}</style><script>var a=1;</script></head>
<body><nav class="ltx_page_navbar">Back to arXiv</nav>
<div class="ltx_page_main"><article class="ltx_document">
<h1 class="ltx_title ltx_title_document">Tiny Speech: Distilled Models for Phones</h1>
<div class="ltx_authors"><span class="ltx_creator">Ana Smith</span></div>
<div class="ltx_abstract"><h6 class="ltx_title ltx_title_abstract">Abstract</h6><p class="ltx_p">We distil speech models.</p></div>
<section id="S1" class="ltx_section"><h2 class="ltx_title ltx_title_section"><span class="ltx_tag ltx_tag_section">1 </span>Introduction</h2>
<div id="S1.p1" class="ltx_para"><p class="ltx_p">Speech recognition on phones is hard because memory is small &amp; batteries are weak.
We cut memory use by 48% with a loss <math alttext="\\mathcal{L}_{KD}" display="inline"><semantics><mi>L</mi><annotation>junk</annotation></semantics></math> from a teacher.</p></div>
</section>
<section id="S4" class="ltx_section"><h2 class="ltx_title ltx_title_section"><span class="ltx_tag ltx_tag_section">4 </span>Experiments</h2>
<section id="S4.SS1" class="ltx_subsection"><h3 class="ltx_title ltx_title_subsection"><span class="ltx_tag">4.1 </span>Setup</h3>
<div class="ltx_para"><p class="ltx_p">We train on 8 A100 GPUs for two days. Evaluation uses LibriSpeech test-clean.</p></div>
<figure class="ltx_table"><table class="ltx_tabular"><tr><th>Model</th><th>WER</th></tr><tr><td>Ours</td><td>4.1</td></tr></table>
<figcaption class="ltx_caption">Table 1: Word error rate on LibriSpeech.</figcaption></figure>
</section></section>
<section id="S5" class="ltx_section"><h2 class="ltx_title ltx_title_section"><span class="ltx_tag">5 </span>Limitations</h2>
<div class="ltx_para"><p class="ltx_p">The model struggles with heavily accented speech.</p></div></section>
<section id="Sx1" class="ltx_section"><h2 class="ltx_title ltx_title_section">Acknowledgements</h2>
<div class="ltx_para"><p class="ltx_p">We thank our funders.</p></div></section>
<section id="bib" class="ltx_bibliography"><h2 class="ltx_title ltx_title_bibliography">References</h2>
<ul><li class="ltx_bibitem">Some cited paper, 2020.</li></ul></section>
</article></div><footer class="ltx_page_footer">Generated by LaTeXML</footer></body></html>`;

test("entities are decoded", () => {
  assert.equal(decode("a &amp; b &lt;c&gt; &#8211; &#x2014; &nbsp;"), "a & b <c> – —  ".replace(" ", " "));
  assert.equal(decode("&bogus; &#99999999;"), "&bogus;  ");
});

test("the page becomes headed blocks, without chrome, references or thanks", () => {
  const blocks = parseArxivHtml(PAGE);
  const headings = blocks.map((b) => b.heading);
  assert.deepEqual(headings, ["1 Introduction", "4.1 Setup", "5 Limitations"]);
  const all = blocks.map((b) => b.body).join("\n");
  assert.match(all, /memory is small & batteries are weak/);
  assert.match(all, /\\mathcal\{L\}_\{KD\}/); // maths kept as its LaTeX
  assert.match(all, /Model \| WER/); // table rows kept
  assert.match(all, /Table 1: Word error rate/);
  for (const gone of ["Back to arXiv", "var a", "Ana Smith", "We thank", "Some cited paper", "LaTeXML", "junk"]) {
    assert.ok(!all.includes(gone), gone);
  }
});

test("passages stay inside one section and respect the size", () => {
  const long = { heading: "3 Method", body: Array.from({ length: 60 }, (_, i) => `Sentence number ${i} explains a step.`).join(" ") };
  const out = toPassages([long, { heading: "4 Results", body: "Short." }], 300);
  assert.ok(out.length > 3);
  assert.ok(out.every((p) => p.body.length <= 450));
  assert.equal(out[out.length - 1].heading, "4 Results");
  assert.ok(out.slice(0, -1).every((p) => p.heading === "3 Method"));
});

test("error pages are not treated as papers", () => {
  assert.equal(usable(toPassages(parseArxivHtml("<html><body><h1>No HTML for this paper</h1><p>Sorry.</p></body></html>"))), false);
  const big = toPassages(parseArxivHtml(PAGE.replace(/We train on/g, "We train on ".repeat(1) + "x ".repeat(2000) + "We train on")));
  assert.equal(usable(big), true);
});

test("answers name the section their quote came from", () => {
  const passages = [{ heading: "Abstract", body: "We distil speech models." }, ...toPassages(parseArxivHtml(PAGE))];
  const raw = JSON.stringify({ answerable: true, answer: "Eight A100 GPUs for two days.", passage: 1, quote: "We train on 8 A100 GPUs for two days." });
  const a = parseFullAnswer(raw, passages)!;
  assert.equal(a.section, "4.1 Setup"); // the model gave the wrong passage number; the quote decides
  assert.equal(a.quote, "We train on 8 A100 GPUs for two days.");
  const invented = parseFullAnswer(JSON.stringify({ answer: "They used TPUs.", passage: 2, quote: "We used 512 TPUs." }), passages)!;
  assert.equal(invented.quote, null);
  assert.equal(invented.section, null);
  assert.equal(parseFullAnswer('{"answerable": false}', passages)!.answer, NOT_IN_PAPER);
  assert.equal(parseFullAnswer("not json", passages), null);
});

test("prompt input numbers the passages and keeps follow-ups", () => {
  const text = fullInput("T", [{ heading: "Abstract", body: "A." }, { heading: "", body: "B." }], "Q?", { q: "Earlier?", a: "Yes." });
  assert.match(text, /\[0\] Abstract\nA\./);
  assert.match(text, /\[1\] Untitled section\nB\./);
  assert.match(text, /Earlier question: Earlier\?/);
  assert.equal(searchText("What GPUs?", { q: "How long to train?" }), "What GPUs? How long to train?");
});
