"""
renderer.py
Generates beautiful, reader-friendly markdown for each daily digest.
"""

import os
from datetime import datetime
try:
    from .scorer import format_badges, format_authors
except (ImportError, ValueError):
    from scorer import format_badges, format_authors

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIGESTS_DIR = os.path.join(ROOT_DIR, "digests")


def _truncate_abstract(abstract: str, max_sentences: int = 5) -> str:
    """Truncate abstract to first N sentences."""
    # Split on ". " to get sentences
    sentences = abstract.split(". ")
    if len(sentences) <= max_sentences:
        return abstract
    return ". ".join(sentences[:max_sentences]) + "."


def _render_paper_entry(paper: dict, index: int, is_only: bool = False) -> str:
    """Render a single paper entry as rich, uncluttered markdown."""
    title = paper.get("title", "Untitled")
    url = paper.get("url", "#")
    pdf_url = paper.get("pdf_url", "#")
    authors = paper.get("authors", [])
    abstract = paper.get("abstract", "")
    submitted = paper.get("submitted", "")
    categories = paper.get("categories", [])
    badges = paper.get("badges", [])
    why_it_matters = paper.get("why_it_matters", "")
    source = paper.get("source", "arXiv")
    hf_upvotes = paper.get("hf_upvotes", 0)
    arxiv_id = paper.get("id", "")

    # Category chips
    cat_chips = " ".join([f"`{c['emoji']} {c['name']}`" for c in categories[:3]])

    # Status badges
    status_chips = " ".join([f"`{b[0]} {b[1]}`" for b in badges if len(b) >= 2])

    # Authors line
    authors_line = format_authors(authors, max_shown=4)

    # Clean abstract display
    abstract_display = _truncate_abstract(abstract, max_sentences=5)

    # Source & metrics
    source_tag = f"📡 **{source}**"
    if hf_upvotes > 0:
        source_tag += f" &nbsp;•&nbsp; 🔥 **{hf_upvotes} HF Upvotes**"

    hf_papers_url = f"https://huggingface.co/papers/{arxiv_id}" if arxiv_id else "#"

    lines = [
        f"### {index}. [{title}]({url})",
        "",
    ]

    all_chips = []
    if status_chips:
        all_chips.append(status_chips)
    if cat_chips:
        all_chips.append(cat_chips)
    if all_chips:
        lines += [" &nbsp; ".join(all_chips), ""]

    if why_it_matters:
        lines += [
            "> 💡 **Why It Matters**  ",
            f"> {why_it_matters}",
            "",
        ]

    lines += [
        f"- 👥 **Authors:** {authors_line}",
        f"- 📅 **Date:** {submitted} &nbsp;•&nbsp; {source_tag}",
        f"- 🔗 **Links:** [arXiv Abstract]({url}) &nbsp;|&nbsp; [PDF Direct]({pdf_url}) &nbsp;|&nbsp; [HF Community]({hf_papers_url})",
        "",
        "<details>",
        "<summary><b>📖 Abstract (click to expand)</b></summary>",
        "",
        f"> {abstract_display}",
        "",
        "</details>",
        "",
        "---",
        "",
    ]

    return "\n".join(lines)


def render_digest(papers: list[dict], date_str: str, stats: dict) -> str:
    """
    Render the full daily digest markdown document.
    """
    # Header metadata
    weekday = datetime.strptime(date_str, "%Y-%m-%d").strftime("%A")
    total_digests = stats.get("total_digests", 1)
    total_tracked = stats.get("total_papers", len(papers))

    # Gather categories represented today
    today_cats = {}
    for paper in papers:
        for cat in paper.get("categories", []):
            slug = cat["slug"]
            if slug not in today_cats:
                today_cats[slug] = cat

    cat_summary = " · ".join([f"{c['emoji']} {c['name']}" for c in today_cats.values()])

    lines = [
        f"# 🧠 AI Paper Daily — {weekday}, {date_str}",
        "",
        f"> **{len(papers)} top paper{'s' if len(papers) != 1 else ''} curated** from arXiv & HuggingFace Papers  ",
        f"> 📊 Digest #{total_digests:,} · {total_tracked:,} papers tracked since launch",
        "",
        "---",
        "",
    ]

    # Table of Contents
    lines += [
        "## 📋 Table of Contents",
        "",
    ]
    for i, paper in enumerate(papers, 1):
        title_short = paper.get("title", "Untitled")[:65]
        if len(paper.get("title", "")) > 65:
            title_short += "…"
        badge_emojis = " ".join([b[0] for b in paper.get("badges", [])])
        lines.append(f"{i}. [{badge_emojis} {title_short}](#paper-{i}--{_anchor(paper.get('title', ''))})")

    lines += [
        "",
        "---",
        "",
        "## 📄 Today's Papers",
        "",
    ]

    # Paper entries
    for i, paper in enumerate(papers, 1):
        lines.append(_render_paper_entry(paper, i, is_only=(len(papers) == 1)))

    # Footer
    lines += [
        "## 📊 Categories Covered Today",
        "",
        f"> {cat_summary}",
        "",
        "---",
        "",
        "## 🔙 Navigation",
        "",
        "[⬅️ Back to Main README](../README.md) · [📁 Browse All Digests](../digests/) · [📊 View Stats](../stats/stats.json)",
        "",
        "---",
        "",
        f"*Auto-generated by [ai-paper-daily](https://github.com) on {date_str}*  ",
        f"*Sources: [arXiv](https://arxiv.org) · [HuggingFace Papers](https://huggingface.co/papers)*",
        "",
    ]

    return "\n".join(lines)


def _anchor(title: str) -> str:
    """Convert title to GitHub-style anchor."""
    import re
    anchor = title.lower().strip()
    anchor = re.sub(r"[^a-z0-9\s-]", "", anchor)
    anchor = re.sub(r"\s+", "-", anchor)
    return anchor[:50]


def save_digest(content: str, date_str: str) -> str:
    """Save the digest markdown to the digests/ directory."""
    os.makedirs(DIGESTS_DIR, exist_ok=True)
    filepath = os.path.join(DIGESTS_DIR, f"{date_str}.md")
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"✅ Digest saved: {filepath}")
    return filepath


def render_category_page(slug: str, emoji: str, name: str, all_papers: list[dict]) -> str:
    """Render a category landing page with all papers ever tracked for that category."""
    lines = [
        f"# {emoji} {name} — All Papers",
        "",
        f"> All papers tracked in the **{name}** category, newest first.",
        f"> Auto-updated daily by [ai-paper-daily](../README.md).",
        "",
        "---",
        "",
        f"**Total papers:** {len(all_papers)}",
        "",
        "| Date | Title | Authors | Links |",
        "|------|-------|---------|-------|",
    ]

    for paper in sorted(all_papers, key=lambda x: x.get("submitted", ""), reverse=True):
        title = paper.get("title", "Untitled")
        url = paper.get("url", "#")
        pdf_url = paper.get("pdf_url", "#")
        date = paper.get("submitted", "")
        authors = format_authors(paper.get("authors", []), max_shown=2)
        badges_str = " ".join([b[0] for b in paper.get("badges", [])])

        title_cell = f"[{badges_str} {title[:55]}{'…' if len(title) > 55 else ''}]({url})"
        links_cell = f"[arXiv]({url}) · [PDF]({pdf_url})"

        lines.append(f"| {date} | {title_cell} | {authors} | {links_cell} |")

    lines += [
        "",
        "---",
        "",
        "[⬅️ Back to README](../README.md)",
        "",
    ]

    return "\n".join(lines)
